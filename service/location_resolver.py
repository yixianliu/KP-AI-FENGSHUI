#: 行政后缀：从末尾反复剥离，直到不再命中（「北京市朝阳区」→「北京市朝阳」→「北京市」）
_ADMIN_SUFFIX_RE = re.compile(r'(特别行政区|自治区|自治州|省|市|县|区|盟)$')
#: 空白字符（含全角空格），解析前统一剔除
_SPACE_RE = re.compile(r'[\s\u3000]+')


def _strip_admin_suffix(text: str) -> str:
    """反复剥离末尾行政后缀，返回最短可匹配主体。"""
    prev = None
    cur = text
    while cur != prev:
        prev = cur
        cur = _ADMIN_SUFFIX_RE.sub('', cur)
    return cur


def resolve_local(text: str) -> Optional[Tuple[str, float, float]]:
    """把出生地文本解析为内置城市表中的 ``(标准城市名, 经度, 纬度)``。

    Args:
        text: 用户输入的出生地文本，如「乌鲁木齐」「北京市朝阳区」。

    Returns:
        tuple | None: 命中返回 ``(标准城市名, 经度, 纬度)``；无法解析返回 None
        （调用方必须显式提示，不得静默回落默认经纬度）。
    """
    raw = _SPACE_RE.sub('', text or '')
    if not raw:
        return None

    # 1) 完全匹配
    for name, lon, lat in CITY_COORDS:
        if raw == name:
            return name, lon, lat

    # 2) 剥离行政后缀后完全匹配
    stripped = _strip_admin_suffix(raw)
    if stripped:
        for name, lon, lat in CITY_COORDS:
            if stripped == name:
                return name, lon, lat

    # 3) 子串包含匹配：按城市名长度倒序，优先命中更长的城市名
    for name, lon, lat in sorted(CITY_COORDS, key=lambda item: -len(item[0])):
        if name in raw:
            return name, lon, lat

    return None
