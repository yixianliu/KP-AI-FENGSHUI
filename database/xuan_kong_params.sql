-- 三元九运
CREATE TABLE IF NOT EXISTS xuan_kong_yun (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    yun_name TEXT NOT NULL,           -- 上元/中元/下元
    yun_num INTEGER NOT NULL,         -- 一运至九运
    start_year INTEGER NOT NULL,      -- 起运年份
    end_year INTEGER NOT NULL,        -- 止运年份
    description TEXT,
    UNIQUE(yun_num)
);

-- 二十四山
CREATE TABLE IF NOT EXISTS xuan_kong_mountain (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    mountain_name TEXT NOT NULL UNIQUE,   -- 山名
    mountain_num INTEGER NOT NULL,        -- 山向序号（1-24）
    direction_deg REAL,                   -- 方位角度
    wuxing TEXT,                          -- 五行属性
    yun_num INTEGER,                      -- 所属元运（通用）
    UNIQUE(mountain_num)
);

-- 替卦规则
CREATE TABLE IF NOT EXISTS xuan_kong_tigua (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    yun_num INTEGER NOT NULL,             -- 运数
    mountain_num INTEGER NOT NULL,        -- 山向序号
    ti_gua_rule TEXT,                     -- 替卦规则描述
    use_tigua INTEGER DEFAULT 0,          -- 是否用替卦
    UNIQUE(yun_num, mountain_num)
);

